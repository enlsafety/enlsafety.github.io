-- Isolated internal history-import metadata. No client/table API access.
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists private.enl_historical_batches(
 id uuid primary key,
 owner_id text not null,
 erp_confirmed_at timestamptz not null,
 candidates jsonb not null default '[]'::jsonb check(jsonb_typeof(candidates)='array'),
 file_errors jsonb not null default '[]'::jsonb check(jsonb_typeof(file_errors)='array'),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);

create table if not exists private.enl_historical_files(
 batch_id uuid not null references private.enl_historical_batches(id) on delete restrict,
 file_id text not null,
 path text not null,
 name text not null,
 hash text not null,
 size bigint not null check(size>0 and size<=12582912),
 method text not null check(method in ('text','ocr')),
 units jsonb not null check(jsonb_typeof(units)='array'),
 primary key(batch_id,file_id)
);

create table if not exists private.enl_historical_import_audit(
 id bigint generated by default as identity primary key,
 batch_id uuid not null references private.enl_historical_batches(id) on delete restrict,
 actor_id text not null,
 action text not null,
 detail jsonb not null,
 created_at timestamptz not null default now()
);

create index if not exists enl_bulk_batch_updated on private.enl_historical_batches(updated_at desc);
create index if not exists enl_bulk_file_hash on private.enl_historical_files(hash);
create index if not exists enl_bulk_audit_batch on private.enl_historical_import_audit(batch_id,created_at desc);

revoke all on all tables in schema private from public, anon, authenticated;
revoke all on all sequences in schema private from public, anon, authenticated;
alter table private.enl_historical_batches enable row level security;
alter table private.enl_historical_files enable row level security;
alter table private.enl_historical_import_audit enable row level security;

insert into storage.buckets(id,name,public,file_size_limit)
 values('enl-import-originals','enl-import-originals',false,12582912)
 on conflict(id) do nothing;
